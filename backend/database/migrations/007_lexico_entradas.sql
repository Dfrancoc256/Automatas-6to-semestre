-- Añade vocabulario por idioma sin modificar las tablas existentes.
BEGIN;

CREATE TABLE IF NOT EXISTS lexico_entradas (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idioma    varchar(30) NOT NULL,
    palabra   varchar(120) NOT NULL,
    categoria varchar(30) NOT NULL,

    CONSTRAINT ck_lexico_idioma CHECK (idioma IN ('español', 'inglés', 'ruso', 'chino', 'árabe')),
    CONSTRAINT ck_lexico_categoria CHECK (categoria IN ('nombre_propio', 'sustantivo', 'verbo', 'adjetivo', 'pronombre', 'conector', 'preposición')),
    CONSTRAINT ck_lexico_palabra CHECK (length(trim(palabra)) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_lexico_idioma_palabra
    ON lexico_entradas (idioma, lower(palabra));

COMMIT;
